import assert from 'node:assert';import * as A from './src/algorithms.js';
const P=[{id:'P1',arrival:0,burst:5,priority:2},{id:'P2',arrival:1,burst:3,priority:1},{id:'P3',arrival:2,burst:1,priority:3},{id:'P4',arrival:3,burst:2,priority:4}];
const r=a=>A.schedule(P,a,2);
assert.equal(r("FCFS").avgWaiting,4);
assert.equal(r("SJF").avgWaiting,3.25);
assert.equal(r('SRTF').avgWaiting,(6+1+0+2)/4);
assert.equal(r('RR').total,11);assert.equal(r('PRIORITY').rows.find(x=>x.id==='P2').completion,8);
let s=A.pcInit(2);s=A.pcStep(A.pcStep(A.pcStep(s,'P'),'P'),'P');assert.equal(s.buf.length,2);assert.equal(s.blockedP,1);
s=A.pcStep(s,'C');assert.ok(s.buf.length<=2&&s.empty>=0&&s.full>=0);
let m=A.memInit([100,500,200,300,600]);m=A.memAlloc(m,'A',212,'first').mem;assert.equal(m[1].pid,'A');
let b=A.memAlloc(A.memInit([100,500,200,300,600]),'A',212,'best').mem;assert.equal(b.find(x=>x.pid==="A").start,800);
let w=A.memAlloc(A.memInit([100,500,200,300,600]),'A',212,'worst').mem;assert.equal(w.find(x=>x.pid==="A").start,1100);
assert.equal(A.memFree(A.memAlloc(A.memInit([100,200]),'X',100,'first').mem,'X').length,1);
const al=[[0,1,0],[2,0,0],[3,0,2],[2,1,1],[0,0,2]],mx=[[7,5,3],[3,2,2],[9,0,2],[2,2,2],[4,3,3]];
assert.deepEqual(A.safety([3,3,2],al,mx).seq,[1,3,0,2,4]);
const g=A.request([3,3,2],al,mx,1,[1,0,2]);assert.equal(g.granted,true);
assert.equal(A.request(g.avail,g.alloc,mx,0,[0,2,0]).granted,false);
assert.equal(A.safety([0,0,0],al,mx).safe,false);
console.log('all algorithm tests passed');
